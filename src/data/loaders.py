# SIDER
# ---------------------------------------------------------------------------

def load_sider_side_effects(raw_dir: Path) -> pd.DataFrame:
    """Load SIDER side-effect database.

    Expected file: ``data/raw/sider/meddra_all_se.tsv``
    (from the SIDER 4.1 download; no header, so we assign column names).

    Parameters
    ----------
    raw_dir:
        Path to ``data/raw/sider/``.
    """
    path = raw_dir / "meddra_all_se.tsv"
    if not path.exists():
        raise FileNotFoundError(
            f"Expected SIDER file not found: {path}\n"
            "Download from http://sideeffects.embl.de/"
        )
    col_names = [
        "stitch_id_flat",
        "stitch_id_stereo",
        "umls_id_label",
        "meddra_type",
        "umls_id_meddra",
        "side_effect_name",
    ]
    df = _tsv(path, header=None, names=col_names, dtype=str)
    validate_raw_schema(df, "sider_se")
    return df



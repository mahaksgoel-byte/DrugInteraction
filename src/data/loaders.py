"""
loaders.py – Raw data loaders for every source.

CONTRACT: Every loader
  1. Reads the raw file(s) for one source.
  2. Calls ``validate_raw_schema`` (BEFORE touching the data).
  3. Returns a plain ``pd.DataFrame`` with ONLY the expected columns selected
     (extra columns are retained but not relied on).
  4. Does NOT clean, transform, or merge anything – that happens in
     ``cleaner.py`` and ``harmoniser.py``.

This separation means loaders can be re-run at any time without side effects.
"""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from .schema_validator import validate_raw_schema

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _csv(path: Path, **kwargs) -> pd.DataFrame:
    """Load a CSV file with basic error reporting."""
    if not path.exists():
        raise FileNotFoundError(
            f"Expected raw file not found: {path}\n"
            "Run the download step first (Step 2.1 of plan.md)."
        )
    df = pd.read_csv(path, **kwargs)
    logger.debug("Loaded %s  →  shape %s", path.name, df.shape)
    return df


def _tsv(path: Path, **kwargs) -> pd.DataFrame:
    """Load a TSV file."""
    return _csv(path, sep="\t", **kwargs)


# ---------------------------------------------------------------------------
# DDInter
# ---------------------------------------------------------------------------

def load_ddinter(raw_dir: Path) -> pd.DataFrame:
    """Load and concatenate DDInter code_A and code_B CSV files.

    Both files share the same schema.  We concatenate them and drop duplicates
    so that any pair appearing in both files is kept once.

    Parameters
    ----------
    raw_dir:
        Path to ``data/raw/ddinter/``.

    Returns
    -------
    pd.DataFrame
        Validated DDInter interactions, no deduplication yet.
    """
    file_a = raw_dir / "ddinter_downloads_code_A.csv"
    file_b = raw_dir / "ddinter_downloads_code_B.csv"

    dfs = []
    for path in [file_a, file_b]:
        if path.exists():
            df_part = _csv(path, dtype=str)
            validate_raw_schema(df_part, "ddinter")
            dfs.append(df_part)
        else:
            logger.warning("DDInter file not found, skipping: %s", path)

    if not dfs:
        raise FileNotFoundError(
            f"No DDInter files found in {raw_dir}. "
            "Expected ddinter_downloads_code_A.csv and/or "
            "ddinter_downloads_code_B.csv"
        )

    combined = pd.concat(dfs, ignore_index=True)
    logger.info("DDInter combined: %d rows from %d file(s)", len(combined), len(dfs))
    return combined



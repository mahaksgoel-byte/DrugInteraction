# STRING
# ---------------------------------------------------------------------------

def load_string_ppi(raw_dir: Path, *, min_score: int = 700) -> pd.DataFrame:
    """Load STRING protein–protein interaction file and pre-filter by score.

    Expected file: ``data/raw/string/protein.links.v12.0.txt.gz``
    (or uncompressed .txt; gzip is handled transparently by pandas).

    Parameters
    ----------
    raw_dir:
        Path to ``data/raw/string/``.
    min_score:
        Minimum combined_score to retain (plan.md: ≥ 700).  NOTE: this is the
        only pre-filter applied here; no other transformation is performed.
    """
    candidates = list(raw_dir.glob("protein.links*.txt*"))
    if not candidates:
        raise FileNotFoundError(
            f"No STRING PPI file found in {raw_dir}. "
            "Download 'protein.links.v*.txt.gz' from string-db.org."
        )
    path = sorted(candidates)[-1]  # take the latest version if multiple
    df = _tsv(path, dtype={"combined_score": int})
    validate_raw_schema(df, "string_ppi")
    # Pre-filter only – score threshold is the one permitted filter at load time
    before = len(df)
    df = df[df["combined_score"] >= min_score].reset_index(drop=True)
    logger.info(
        "STRING PPI: kept %d / %d edges with combined_score ≥ %d",
        len(df), before, min_score,
    )
    return df


